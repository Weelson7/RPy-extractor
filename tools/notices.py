"""Generate THIRD_PARTY_NOTICES.md from viwo/data/tools.json (tools ViWo downloads on demand).

Usage: python tools/notices.py          # writes the file
       python tools/notices.py --check  # exit 1 when the file is out of date
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "viwo" / "data" / "tools.json"
OUT = ROOT / "THIRD_PARTY_NOTICES.md"
HEAD = """# Third-party notices

ViWo bundles none of these. It downloads each one on demand from the pinned URL below, checks
the size and sha256 recorded in `viwo/data/tools.json`, and installs it into `third_party/<id>/`.
Every tool keeps its own license and its own authors; ViWo's authors are not theirs, and GPL
tools only ever run as separate processes. See README, "Legal and disclaimer", for the use and
misuse disclaimer that covers these tools and the community scripts and indexes.

Generated by `python tools/notices.py`; do not edit by hand.

## Executables

| id | version | license | Windows | Linux |
|----|---------|---------|---------|-------|
"""
TAIL = """
## Python packages (pip, pinned)

| package | pin |
|---------|-----|
"""


def render() -> str:
    data = json.loads(MANIFEST.read_text(encoding="utf-8"))
    rows = []
    for dep, entry in sorted(data["tools"].items()):
        cells = []
        for plat in ("windows", "linux"):
            spec = entry.get(plat) or {}
            url = spec.get("url", "")
            cells.append(f"[{url.rsplit('/', 1)[-1]}]({url})" if url else spec.get("from", "-"))
        rows.append(
            f"| {dep} | {entry.get('version', '')} | {entry.get('license', '')} | "
            f"{cells[0]} | {cells[1]} |"
        )
    pins = [f"| {name} | `{pin}` |" for name, pin in sorted(data["python"].items())]
    return HEAD + "\n".join(rows) + "\n" + TAIL + "\n".join(pins) + "\n"


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.is_file() else ""
        if current != text:
            print("THIRD_PARTY_NOTICES.md is out of date: run python tools/notices.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
