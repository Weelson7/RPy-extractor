"""Distro config files (doc 9): generator and strict checker.

A distro is an ini file named `<os>-<profile>.ini` in `distros/`: 2 OS layers x the profiles,
which are the built-ins' own (a plugin names one in its manifest) plus `custom` and `mixed`.
`startup.ini` selects one with `[startup] base = distros/<os>-<profile>.ini`.

Rules the generator follows and `check` enforces:
 1. File names match NAME exactly (lowercase, known OS and profile).
 2. Generated files start with MARKER; the generator never overwrites a file without it.
 3. Only known sections and keys; plugin, slot and backend ids exist in the registry; every
    backend serves its slot's family; no secret-looking option keys.
 4. Output is deterministic: sorted entries, UTF-8, LF line endings, one trailing newline.
 5. Every generated file loads with zero problems before it is written.
"""

import re
import tempfile
from pathlib import Path

from viwo import CONTRACT_VERSION

from .ini import KNOWN_SECTIONS, load_ini
from .registry import BUILTIN_PLUGINS, collect, core_sources, known_ids, load_enabled

OSES = ("linux", "windows")
SHARED = ("custom", "mixed")  # every built-in without a profile of its own; everything
NAME = re.compile(r"^(linux|windows)-([a-z][a-z0-9_-]*)\.ini$")
MARKER = "; Generated by `viwo config generate` - edit startup.ini instead of this file."


def tool_example(os_id: str, spec) -> str:
    """A plausible path for the commented [tools] line, from the dependency's own names."""
    names = spec.executables_for(os_id)
    exe = names[0] if names else spec.dep_id
    if os_id == "windows":
        folder = spec.install_dirs[0] if spec.install_dirs else exe
        return f"C:/Program Files/{folder}/{exe}.exe"
    return f"/usr/bin/{exe}"


def _registry():
    plugins, _ = load_enabled({})
    return plugins, collect(*core_sources(), plugins)


def own_profiles() -> dict[str, str]:
    """Profile -> plugin id: the built-ins whose manifest names a distro profile of their own."""
    plugins, _ = load_enabled({})
    return {
        p.manifest.profile: i
        for i, p in plugins.items()
        if p.manifest.profile and i in BUILTIN_PLUGINS
    }


def profiles() -> tuple[str, ...]:
    return (*sorted(own_profiles()), *SHARED)


def enabled_for(profile: str) -> dict[str, bool]:
    """mixed = everything; a plugin's own profile = that plugin; custom = every other built-in."""
    own = own_profiles()
    custom = {p for p in BUILTIN_PLUGINS if p not in own.values() and p != "generic"}
    wanted = (
        set(BUILTIN_PLUGINS)
        if profile == "mixed"
        else custom
        if profile == "custom"
        else {own.get(profile, profile)}
    )
    return {pid: pid == "generic" or pid in wanted for pid in sorted(BUILTIN_PLUGINS)}


def render(os_id: str, profile: str) -> str:
    plugins, (slots, backends, _) = _registry()
    on = enabled_for(profile)
    owners = {"core"} | {p for p, enabled in on.items() if enabled}
    lines = [
        MARKER,
        f"; viwo contract {CONTRACT_VERSION} - distro {os_id}-{profile}",
        "",
        "[startup]",
    ]
    lines += [f"os = {os_id}", f"profile = {profile}", "features = extraction, sorting, merger", ""]
    lines += [
        "[plugins]",
        *(f"{pid} = {'on' if v else 'off'}" for pid, v in on.items()),
        "",
        "[slots]",
    ]
    for sid in sorted(s for s, d in slots.items() if d.owner in owners):
        d = slots[sid]
        spare = d.default_spare if d.default_spare in backends else ""
        spare = spare if spare and backends[spare].owner in owners else ""  # its plugin is on
        lines.append(f"{sid} = {d.default_main or 'none'}" + (f", {spare}" if spare else ""))
    deps = {
        spec.dep_id: spec
        for b in backends.values()
        if b.owner in owners
        for spec in b.dependencies()
        if spec.kind != "python"  # Python packages are installed with pip, not pointed at
    }
    lines += ["", "[tools]", "; <dependency id> = path (found on PATH when left out)"]
    lines += [f"; {dep} = {tool_example(os_id, deps[dep])}" for dep in sorted(deps)]
    return "\n".join(lines) + "\n"


def check(path: Path) -> list[str]:
    """Strict problems with one config file (empty list = valid)."""
    known = profiles()
    named = NAME.match(path.name)
    errors = (
        []
        if path.name == "startup.ini" or (named and named.group(2) in known)
        else [f"{path.name}: name must be <os>-<profile>.ini, a profile of {'|'.join(known)}"]
    )
    try:
        config = load_ini(path)
    except Exception as exc:  # noqa: BLE001 (any parse failure is a finding)
        return errors + [str(exc)]
    plugins, (slots, backends, _) = _registry()
    ids = known_ids(config.custom_dirs)
    errors += list(config.problems)
    errors += [
        f"[plugins] unknown plugin '{p}'"
        for p in config.plugins
        if p.removeprefix("custom.") not in ids
    ]
    for sid, (main, spare) in config.slots.items():
        if sid not in slots:
            errors.append(f"[slots] unknown slot '{sid}'")
            continue
        for bid in (b for b in (main, spare) if b):
            backend = backends.get(bid)
            if backend is None or slots[sid].family not in backend.families:
                errors.append(f"[slots] {sid}: '{bid}' is not a {slots[sid].family} backend")
    errors += [f"[options.{p}] unknown plugin" for p in config.options if p not in ids]
    if config.os_id not in ("auto", *OSES) or config.profile not in known:
        errors.append(f"[startup] os/profile must be auto|{'|'.join(OSES)} / {'|'.join(known)}")
    return errors


def generate(out: Path, force_names: tuple[str, ...] = ()) -> dict[str, list[str]]:
    """Write the 12 distro files into out. Returns {file name: problems} (empty = written)."""
    out.mkdir(parents=True, exist_ok=True)
    report: dict[str, list[str]] = {}
    for os_id in OSES:
        for profile in profiles():
            name, text = f"{os_id}-{profile}.ini", render(os_id, profile)
            target = out / name
            if target.exists() and not target.read_text(encoding="utf-8").startswith(MARKER):
                report[name] = ["exists and was not generated: left untouched"]
                continue
            with tempfile.TemporaryDirectory() as tmp:  # rule 5: validate before writing
                probe = Path(tmp) / name
                probe.write_bytes(text.encode("utf-8"))
                problems = check(probe)
            if not problems:
                target.write_bytes(text.encode("utf-8"))  # bytes: LF on every OS (rule 4)
            report[name] = problems
    return report


__all__ = ["KNOWN_SECTIONS", "MARKER", "NAME", "OSES", "check", "generate", "profiles", "render"]
